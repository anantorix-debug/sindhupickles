// Generates db/imports/live-wordpress-products.sql from the local WordPress archive (data/wordpress-archive).
//   node scripts/emit-live-products-sql.mjs
// It reads no database and no credentials. The output is a ONE-TIME import you run by hand (phpMyAdmin -> Import) on the
// live database; it is NOT a migration and never runs automatically on a deploy.
//
// What it adds: the 16 old products as 16 separate products with the SAME /product/<slug> addresses and prices, each with
// one pack (100g or 250g), its old SEO title/description, and a record of the old address. No photos and no static files:
// upload each photo in Admin -> Products. Stock is 0 (the old site did not publish quantities): set it in Admin -> Inventory.
// Safe to run twice and safe on a shop that already has data: every row is INSERT ... SELECT ... WHERE NOT EXISTS, so
// anything that already exists is left exactly as it is and nothing is ever updated or deleted.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const ARCHIVE = process.env.WP_ARCHIVE ?? "data/wordpress-archive";
const OUT = "db/imports/live-wordpress-products.sql";

const decode = (s) =>
  s.replace(/&#0?39;|&#8217;|&rsquo;/g, "'").replace(/&amp;|&#038;/g, "&").replace(/&quot;|&#8220;|&#8221;/g, '"').replace(/&nbsp;/g, " ").replace(/&#8211;|&ndash;/g, "–").replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const htmlToText = (h) =>
  decode(
    (h ?? "")
      .replace(/<li[^>]*>/gi, "\n• ")
      .replace(/<\/(p|h[1-6]|ul|ol|div)>/gi, "\n")
      .replace(/<br[^>]*>/gi, "\n")
      .replace(/<[^>]+>/g, ""),
  )
    .replace(/[ \t]+/g, " ")
    .replace(/\n[ \t]+/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();

const FLAVOUR = [
  [/chicken/i, "chicken-pickles"],
  [/mutton/i, "mutton-pickles"],
  [/chenna kunni|prawn|shrimp/i, "prawn-pickles"],
  [/fish|tuna|nethili|pal sura|dryfish/i, "fish-pickles"],
];
const CATEGORIES = [
  ["Chicken Pickles", "chicken-pickles"],
  ["Mutton Pickles", "mutton-pickles"],
  ["Fish Pickles", "fish-pickles"],
  ["Prawn Pickles", "prawn-pickles"],
];

const readJson = (f) => JSON.parse(readFileSync(path.join(ARCHIVE, "api", f), "utf8"));
const seoRows = new Map(
  readJson("seo.json").map((r) => [new URL(r.url).pathname.replace(/\/$/, "").split("/").pop(), { title: decode(r.title ?? "").trim(), description: decode(r.desc ?? "").trim() }]),
);
/** SQL string literal (MySQL / MariaDB): quotes doubled, backslashes doubled. */
const q = (v) => (v === null || v === undefined || v === "" ? "NULL" : `'${String(v).replace(/\\/g, "\\\\").replace(/'/g, "''")}'`);

const rows = [];
for (const p of readJson("products.json")) {
  const minor = Number(p.prices.currency_minor_unit ?? 2);
  const pricePaise = Math.round(Number(p.prices.price) / 10 ** (minor - 2));
  const flavour = FLAVOUR.find(([re]) => re.test(p.name))?.[1];
  const pack = p.name.match(/(\d+)\s*g(?![a-z])/i);
  if (!flavour || !pack || !(pricePaise > 0)) throw new Error(`cannot map product ${p.slug}`);
  const grams = Number(pack[1]);
  const seo = seoRows.get(p.slug);
  rows.push({
    wpId: p.id, slug: p.slug, name: decode(p.name), flavour, pricePaise, grams, label: `${grams}g`,
    short: htmlToText(p.short_description).slice(0, 500), description: htmlToText(p.description) || decode(p.name), url: new URL(p.permalink).pathname,
    metaTitle: (seo?.title ?? "").slice(0, 255), metaDescription: (seo?.description ?? "").slice(0, 500),
  });
}
rows.sort((a, b) => a.wpId - b.wpId);

const parts = [`-- Sindhu's Pickles: the ${rows.length} real products from the old WordPress shop, with the same /product/<slug> web addresses.
-- ONE-TIME import, run by hand: hPanel -> Databases -> phpMyAdmin -> select your database -> Import (or paste into the SQL tab).
-- Generated by scripts/emit-live-products-sql.mjs from data/wordpress-archive. Do not edit by hand.
-- Additive only: every row is INSERT ... WHERE NOT EXISTS, so anything that already exists is left untouched, nothing is
-- updated or deleted, and running it twice adds nothing. No photos: upload them in Admin -> Products. Stock is 0: set it in Admin -> Inventory.

-- the four flavour categories (an existing category is not touched)
INSERT IGNORE INTO categories (name, slug, position, active) VALUES
${CATEGORIES.map(([name, slug], i) => `  (${q(name)}, ${q(slug)}, ${i + 1}, 1)`).join(",\n")};
`];
for (const r of rows) {
  const sku = `WP-${r.wpId}`;
  const vsku = `WP-${r.wpId}-${r.label}`;
  parts.push(`-- ${r.name}  (₹${r.pricePaise / 100})
INSERT INTO products (name, slug, description, short_description, sku, category_id, price_paise, status, featured, rating_avg, review_count, spice_level, created_at, updated_at)
SELECT ${q(r.name)}, ${q(r.slug)}, ${q(r.description)}, ${q(r.short)}, ${q(sku)}, c.id, ${r.pricePaise}, 'ACTIVE', 0, 0, 0, 0, NOW(3), NOW(3)
FROM categories c WHERE c.slug = ${q(r.flavour)} AND NOT EXISTS (SELECT 1 FROM products x WHERE x.slug = ${q(r.slug)} OR x.sku = ${q(sku)});
INSERT INTO product_variants (product_id, sku, label, size, weight_grams, position, active, created_at, updated_at)
SELECT p.id, ${q(vsku)}, ${q(r.label)}, ${q(r.label)}, ${r.grams}, 0, 1, NOW(3), NOW(3)
FROM products p WHERE p.slug = ${q(r.slug)} AND NOT EXISTS (SELECT 1 FROM product_variants v WHERE v.product_id = p.id);
INSERT INTO inventory (variant_id, on_hand, reserved, low_stock_threshold, updated_at)
SELECT v.id, 0, 0, 10, NOW(3) FROM product_variants v WHERE v.sku = ${q(vsku)} AND NOT EXISTS (SELECT 1 FROM inventory i WHERE i.variant_id = v.id);
INSERT INTO product_seo (product_id, meta_title, meta_description)
SELECT p.id, ${q(r.metaTitle)}, ${q(r.metaDescription)} FROM products p WHERE p.slug = ${q(r.slug)} AND NOT EXISTS (SELECT 1 FROM product_seo s WHERE s.product_id = p.id);
INSERT INTO wp_import_map (wp_id, wp_type, wp_slug, wp_url, product_id)
SELECT ${r.wpId}, 'product', ${q(r.slug)}, ${q(r.url)}, p.id FROM products p WHERE p.slug = ${q(r.slug)} AND NOT EXISTS (SELECT 1 FROM wp_import_map w WHERE w.wp_id = ${r.wpId} AND w.wp_type = 'product');
`);
}
mkdirSync(path.dirname(OUT), { recursive: true });
writeFileSync(OUT, parts.join("\n"));
console.log(`wrote ${OUT}: ${rows.length} products, sum of prices ₹${rows.reduce((s, r) => s + r.pricePaise, 0) / 100}`);
