// Packs db/migrations/*.sql into scripts/migrations.generated.mjs so the running app carries its own migrations
// (a deployed server may not have the db/ folder). Runs automatically before `npm run dev` and `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "db", "migrations");
const migrations = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((name) => ({ name, sql: readFileSync(join(dir, name), "utf8").replace(/\r\n/g, "\n") }));

const out = `// GENERATED by scripts/gen-migrations.mjs from db/migrations/*.sql. Do not edit by hand.\nexport const migrations = ${JSON.stringify(migrations, null, 2)};\n`;
writeFileSync(join(root, "scripts", "migrations.generated.mjs"), out);
console.log(`[migrate] packed ${migrations.length} migration file(s): ${migrations.map((m) => m.name).join(", ")}`);
