// Builds src/content/legacy-seo.ts from the local WordPress archive (data/wordpress-archive).
// Keyed by product slug only — no site URLs are written into the code. Re-run after refreshing the archive:
//   node scripts/build-legacy-seo.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = "data/wordpress-archive/api";
const decode = (s = "") => s.replace(/&#0?39;|&#8217;|&rsquo;/g, "'").replace(/&amp;|&#038;/g, "&").replace(/&quot;/g, '"').replace(/&#8211;|&ndash;/g, "–").replace(/\s+/g, " ").trim();

const products = JSON.parse(readFileSync(`${dir}/products.json`, "utf8"));
const seo = new Map(JSON.parse(readFileSync(`${dir}/seo.json`, "utf8")).map((r) => [r.url.replace(/\/$/, "").split("/").pop(), r]));

// Real search phrases have a space ("buy mutton pickle"); the old site also had CamelCase hashtags
// ("SindhuPickle") that aren't search terms, so they're kept in the archive but not in the code.
const isPhrase = (t) => /\s/.test(t.trim()) && !/^[A-Z][a-z]+([A-Z][a-z]+)+$/.test(t.trim());

const entries = {};
const freq = new Map();
for (const p of products) {
  const r = seo.get(p.slug);
  const keywords = [...new Set(p.tags.map((t) => decode(t.name)).filter(isPhrase).map((t) => t.toLowerCase()))];
  for (const k of keywords) freq.set(k, (freq.get(k) ?? 0) + 1);
  entries[p.slug] = { title: decode(r?.title).replace(/\s*\|\s*Sindhu'?s\s*$/i, "").trim(), description: decode(r?.desc), keywords };
}

// Generic, store-wide phrases: used on more than one flavour of product.
const generic = (k) => /non.?veg|salem|india/.test(k);
const siteKeywords = [...freq]
  .filter(([k, n]) => n >= 2 && (generic(k) || /homemade|achar|pickle online/.test(k)))
  .map(([k]) => k)
  .sort((a, b) => Number(generic(b)) - Number(generic(a)) || a.localeCompare(b))
  .slice(0, 16);

const out = `/**
 * SEO copy carried over from the previous WordPress/Rank Math setup (generated by scripts/build-legacy-seo.mjs from
 * data/wordpress-archive). Keyed by product slug. Titles/descriptions here are the proven snippets; keywords are the
 * search phrases the old product pages were tagged with.
 */
export interface LegacySeo {
  title: string;
  description: string;
  keywords: string[];
}

export const legacySeo: Record<string, LegacySeo> = ${JSON.stringify(entries, null, 2)};

/** Store-wide phrases for the home page / site metadata. */
export const siteKeywords: string[] = ${JSON.stringify(siteKeywords, null, 2)};
`;
writeFileSync("src/content/legacy-seo.ts", out);
console.log(`products: ${Object.keys(entries).length}, distinct phrases: ${freq.size}, site keywords: ${siteKeywords.length}`);
console.log("site keywords:", siteKeywords.join(" | "));
